#!/usr/bin/python3 -I
"""Генерирует ui/RandomCandidates.js из backend/customizer/fx_catalog.py (issue #3).

  /usr/bin/python3 -I scripts/gen_random_candidates.py          # переписать файл
  /usr/bin/python3 -I scripts/gen_random_candidates.py --check  # сверить: рассинхрон → exit 1

Каталог — единственный источник переходов; сгенерированный файл не правится руками.
Рассинхрон ловит tests/test_transition_metadata.py.
"""
import os
import re
import sys

PLUGIN = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(PLUGIN, "backend"))

from customizer.fx_catalog import FX_RANDOM_OK  # noqa: E402

OUT = os.path.join(PLUGIN, "ui", "RandomCandidates.js")

_IDENT = re.compile(r"[A-Za-z_$][A-Za-z0-9_$]*\Z")

_TEMPLATE = '''/** @file Keeps keyboard random-pick eligibility separate from row rendering.
 *
 * GENERATED by scripts/gen_random_candidates.py from backend/customizer/fx_catalog.py.
 * Do not edit by hand: a new transition goes into the catalog, then this file is
 * regenerated; tests/test_transition_metadata.py fails on drift.
 */
.pragma library

// Wallpaper FX shares one list between transitions and operations; fail closed to transitions.
var WALLPAPER_FX_TRANSITIONS = {
%(entries)s
};

var ACTION_VALUE = /^(pick-|toggle$|next$|save$|regen-thumbs$|tweak:|section:|cache$|prune$|none$|dir:|current$|arch$|test:|open$)/;

/**
 * Report whether a row can be selected by the keyboard random action.
 *
 * @param {string} categoryKey - Current category identifier.
 * @param {string} value - Backend row value, not its translated label.
 * @param {boolean} current - Whether this row is already the active choice.
 * @param {boolean} selected - Whether this row is highlighted in the list.
 * @returns {boolean} True only for an eligible non-current, non-action row.
 */
function isCandidate(categoryKey, value, current, selected) {
  if (current || selected || ACTION_VALUE.test(value)) return false;
  if (categoryKey === "wallpaper-fx" && WALLPAPER_FX_TRANSITIONS[value] !== true) return false;
  return true;
}
'''


def _key(value):
    return value if _IDENT.match(value) else '"%s"' % value


def render():
    entries = ",\n".join("  %s: true" % _key(v) for v in FX_RANDOM_OK) + ","
    return _TEMPLATE % {"entries": entries}


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        try:
            current = open(OUT, encoding="utf-8").read()
        except OSError:
            current = None
        if current != text:
            print("RandomCandidates.js is stale: run scripts/gen_random_candidates.py")
            return 1
        print("RandomCandidates.js matches the catalog")
        return 0
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote %s (%d transitions)" % (OUT, len(FX_RANDOM_OK)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
